def configure_document(document: Document) -> None:
    section = document.sections[0]
    section.page_width, section.page_height = Mm(210), Mm(297)
    section.orientation = WD_ORIENT.PORTRAIT
    section.top_margin, section.bottom_margin = Inches(0.70), Inches(0.65)
    section.left_margin = section.right_margin = Inches(0.75)
    section.header_distance = section.footer_distance = Inches(0.30)
    set_section_columns(section, 1)
    configure_header_footer(section)

    styles = document.styles
    normal = styles["Normal"]
    normal.font.name = BODY_FONT
    for key in ("ascii", "hAnsi", "eastAsia", "cs"):
        normal._element.rPr.rFonts.set(qn(f"w:{key}"), BODY_FONT)
    language = OxmlElement("w:lang")
    language.set(qn("w:val"), "en-GB")
    language.set(qn("w:eastAsia"), "en-GB")
    normal._element.rPr.append(language)
    normal.font.size = Pt(9.15)
    normal.font.color.rgb = RGBColor.from_string(INK)
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    normal.paragraph_format.line_spacing = 1.04
    normal.paragraph_format.space_after = Pt(3.2)
    normal.paragraph_format.widow_control = True
    specs = {
        "Title": (BODY_FONT, 18.5, NAVY, True, False, WD_ALIGN_PARAGRAPH.CENTER, 0, 7),
        "Subtitle": (BODY_FONT, 10.1, MUTED, False, True, WD_ALIGN_PARAGRAPH.CENTER, 0, 5),
        "Heading 1": (BODY_FONT, 12.0, NAVY, True, False, WD_ALIGN_PARAGRAPH.LEFT, 10, 3),
        "Heading 2": (BODY_FONT, 10.0, INK, True, False, WD_ALIGN_PARAGRAPH.LEFT, 7, 2),
        "Heading 3": (BODY_FONT, 9.3, NAVY, True, True, WD_ALIGN_PARAGRAPH.LEFT, 5, 1),
        "Caption": (BODY_FONT, 7.5, MUTED, False, False, WD_ALIGN_PARAGRAPH.LEFT, 2, 6),
        "Quote": (BODY_FONT, 8.7, NAVY, False, True, WD_ALIGN_PARAGRAPH.LEFT, 4, 4),
    }
    for name, (font, size, colour, bold, italic, align, before, after) in specs.items():
        style = styles[name]
        style.font.name = font
        for key in ("ascii", "hAnsi", "eastAsia", "cs"):
            style._element.rPr.rFonts.set(qn(f"w:{key}"), font)
        style.font.size = Pt(size)
        style.font.color.rgb = RGBColor.from_string(colour)
        style.font.bold, style.font.italic = bold, italic
        style.paragraph_format.alignment = align
        style.paragraph_format.space_before, style.paragraph_format.space_after = Pt(before), Pt(after)
        style.paragraph_format.keep_with_next = name.startswith("Heading")
    for name in ("List Bullet", "List Number"):
        style = styles[name]
        style.font.name = BODY_FONT
        for key in ("ascii", "hAnsi", "eastAsia", "cs"):
            style._element.rPr.rFonts.set(qn(f"w:{key}"), BODY_FONT)
        style.font.size = Pt(8.9)
        style.paragraph_format.left_indent = Inches(0.16)
        style.paragraph_format.first_line_indent = Inches(-0.12)
        style.paragraph_format.space_after = Pt(1.8)
    for node in styles.element.xpath(".//w:lang"):
        node.set(qn("w:val"), "en-GB")
        node.set(qn("w:eastAsia"), "en-GB")


