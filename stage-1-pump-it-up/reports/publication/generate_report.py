def add_body(document: Document, text: str, *, lead: str | None = None) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if lead and text.startswith(lead):
        run = paragraph.add_run(lead)
        set_run_font(run, BODY_FONT, 9.15, INK, True)
        paragraph.add_run(text[len(lead):])
    else:
        paragraph.add_run(text)
    set_keep_together(paragraph)


def add_bullet(document: Document, text: str) -> None:
    paragraph = document.add_paragraph(style="List Bullet")
    paragraph.add_run(text)
    set_keep_together(paragraph)


def add_heading(document: Document, text: str, level: int = 1) -> None:
    paragraph = document.add_heading(text, level=level)
    set_keep_with_next(paragraph)


def add_column_break(document: Document) -> None:
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.add_run().add_break(WD_BREAK.COLUMN)


def add_figure(document: Document, path: Path, number: int, title: str, caption: str, alt: str, width: float = 6.70) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_before = Pt(1)
    paragraph.paragraph_format.space_after = Pt(0)
    shape = paragraph.add_run().add_picture(str(path), width=Inches(width))
    add_alt_text(shape, f"Figure {number}. {title}", alt)
    set_keep_with_next(paragraph)
    cap = document.add_paragraph(style="Caption")
    run = cap.add_run(f"Figure {number} | {title}. ")
    set_run_font(run, BODY_FONT, 7.5, NAVY, True)
    cap.add_run(caption)
    set_keep_together(cap)


def add_table(document: Document, headers: Sequence[str], rows: Iterable[Sequence[str]], widths: Sequence[int], caption: tuple[int, str] | None = None) -> None:
    if caption:
        number, title = caption
        cap = document.add_paragraph(style="Caption")
        run = cap.add_run(f"Table {number} | {title}")
        set_run_font(run, BODY_FONT, 7.5, NAVY, True)
        cap.paragraph_format.space_after = Pt(2)
        set_keep_with_next(cap)
    table = document.add_table(rows=1, cols=len(headers))
    centred_headers = {"Rows", "Wt.", "Fit + predict", "Dev.", "Local test", "Public"}
    header = table.rows[0]
    set_repeat_table_header(header)
    for index, text in enumerate(headers):
        cell = header.cells[index]
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        set_cell_shading(cell, NAVY)
        paragraph = cell.paragraphs[0]
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if text in centred_headers else WD_ALIGN_PARAGRAPH.LEFT
        run = paragraph.add_run(text)
        set_run_font(run, BODY_FONT, 7.1, WHITE, True)
    for row_index, values in enumerate(rows):
        row = table.add_row()
        row.height_rule = WD_ROW_HEIGHT_RULE.AT_LEAST
        for index, value in enumerate(values):
            cell = row.cells[index]
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            set_cell_shading(cell, WHITE if row_index % 2 == 0 else PALE)
            paragraph = cell.paragraphs[0]
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if headers[index] in centred_headers else WD_ALIGN_PARAGRAPH.LEFT
            paragraph.paragraph_format.space_after = Pt(0)
            run = paragraph.add_run(str(value))
            set_run_font(run, BODY_FONT, 7.0, INK, index == 0)
            set_cell_border(cell, bottom={"val": "single", "sz": "3", "color": GRID})
    set_table_fixed_widths(table, widths)
    document.add_paragraph().paragraph_format.space_after = Pt(0)


def add_callout(document: Document, label: str, statement: str, colour: str = TEAL) -> None:
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.space_before = Pt(3)
    paragraph.paragraph_format.space_after = Pt(5)
    paragraph.paragraph_format.left_indent = Pt(4)
    paragraph.paragraph_format.right_indent = Pt(4)
    style_boxed_paragraph(paragraph, PALE, colour)
    run = paragraph.add_run(f"{label.upper()}  |  ")
    set_run_font(run, BODY_FONT, 7.2, colour, True)
    run = paragraph.add_run(statement)
    set_run_font(run, BODY_FONT, 8.6, INK, False)
    set_keep_together(paragraph)


