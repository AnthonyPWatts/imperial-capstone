def add_introduction(document: Document) -> None:
    add_heading(document, "1  Introduction", 1)
    add_body(document, "Reliable infrastructure assessment is a classification problem with a consequential error structure. A waterpoint recorded as functional, functional but requiring repair, or non-functional may influence inspection priorities and maintenance planning, yet the three labels are not equally common, separable, or costly to confuse. The Pump It Up benchmark provides a compact setting in which to examine predictive performance, validation design, and the limits of the resulting claims.", lead="Reliable infrastructure assessment")
    add_body(document, "The task contains several recognised sources of machine-learning error: high-cardinality names, partially missing administrative fields, implausible zero values, duplicated semantic encodings, strong geographical structure, and a repair class comprising only 7.27% of labelled observations. Flexible learners can use these signals, but they can also amplify leakage, memorise unstable identities, or produce optimistic estimates after repeated use of the same validation data. The analysis therefore reports model performance, allocation of evidence, rejected candidates, and uncertainty around small improvements.")
    add_body(document, "The study addresses three questions: which model families perform credibly before extensive tuning; whether representation diversity and controlled high-cardinality information improve a strong tree ensemble; and whether development, local-test, and public evidence support the same model ordering. Preprocessing is fitted within folds, candidate changes are assessed against a prespecified promotion rule, and public results are reported alongside local evidence.")
    add_callout(document, "Study scope", "Leakage-controlled validation; a complete candidate ledger; a six-model probability ensemble; paired uncertainty for the final local increments; and a reproducible submission artefact with a cryptographic checksum.")

    add_heading(document, "2  Data and problem formulation", 1)
    add_heading(document, "2.1  Source, unit of analysis and outcome", 2)
    add_body(document, "The data originate from the DrivenData Pump It Up: Data Mining the Water Table competition [1]. Each row represents one Tanzanian waterpoint described by geographical, administrative, management, extraction, payment, quantity, quality, and construction attributes. The labelled set contains 59,400 observations, and the competition set contains 14,850 observations. The response is nominal, with three mutually exclusive classes: functional, functional needs repair, and non-functional.")
    add_body(document, "The primary estimand is predictive: the probability distribution over the three recorded status classes for a previously unseen row drawn under the benchmark’s sampling process. It is not a causal estimand. The analysis does not claim that changing a feature such as management type or payment policy would cause a change in waterpoint condition.")
    add_column_break(document)
    add_table(
        document, ["Partition", "Rows", "Analytical role"],
        [
            ("Development", "47,520", "Fitting, cross-validation, and model selection"),
            ("Local test", "11,880", "Paired final assessment"),
            ("Competition", "14,850", "Frozen submission and public evaluation"),
        ], [1150, 650, 2893], caption=(1, "Partition roles and access constraints"),
    )
